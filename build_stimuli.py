#!/usr/bin/env python3
"""
Rebuild ams_stimuli.js from the PsychoPy spreadsheets.

Only needed if you change a stimulus sheet or the instruction text.
Run it from the folder that holds the .xlsx files:

    python build_stimuli.py            # writes ams_stimuli.js next to this script
    python build_stimuli.py path/to/sheets

Needs openpyxl (pip install openpyxl).
"""
import json
import os
import sys

import openpyxl

SHEET_DIR = sys.argv[1] if len(sys.argv) > 1 else os.getcwd()
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ams_stimuli.js")

INSTRUCTIONS_FILE = "ams_vm_general_instructions_v2025.0303.xlsx"
LANGUAGE_ROW = 0  # 0 = English (same row numbers as the PsychoPy script)

# Same lists as the PsychoPy script ('Before Experiment' code from code_7)
AMS_FILES = {
    "3 or younger": ["ams_task_3yrs_stimulus_sheet_b1.xlsx",
                     "ams_task_3yrs_stimulus_sheet_b2.xlsx",
                     "ams_task_3yrs_stimulus_sheet_b3.xlsx"],
    "4": ["ams_task_4yrs_stimulus_sheet_b1.xlsx",
          "ams_task_4yrs_stimulus_sheet_b2.xlsx",
          "ams_task_4yrs_stimulus_sheet_b3.xlsx"],
    "5": ["ams_task_5yrs_stimulus_sheet_b1.xlsx",
          "ams_task_5yrs_stimulus_sheet_b2.xlsx",
          "ams_task_5yrs_stimulus_sheet_b3.xlsx"],
}
PRACTICE_FILE = "ams_task_practice_stimulus_sheet.xlsx"
SAMPLES_LIST_FILE = "ams_task_samples_files.xlsx"


def read_rows(name):
    """Read a sheet like psychopy.data.importConditions: header row -> list of dicts.
    data_only=True gives the cached result of formulas such as correct_shift."""
    wb = openpyxl.load_workbook(os.path.join(SHEET_DIR, name), data_only=True)
    ws = wb.worksheets[0]
    rows = list(ws.iter_rows(values_only=True))
    header = [h for h in rows[0]]
    out = []
    for r in rows[1:]:
        if all(v is None or v == "" for v in r):
            continue
        d = {}
        for h, v in zip(header, r):
            if h is None:
                continue
            d[str(h)] = v
        # correct_shift is an Excel formula in some sheets: =IF(correct="a","s","l").
        # Recompute it so the site never depends on a cached formula value.
        if d.get("correct") in ("a", "l"):
            d["correct_shift"] = "s" if d["correct"] == "a" else "l"
        out.append(d)
    return out


def main():
    instr_rows = read_rows(INSTRUCTIONS_FILE)
    text = {k: v for k, v in instr_rows[LANGUAGE_ROW].items() if v is not None}

    sample_files = [r["sample_file"] for r in read_rows(SAMPLES_LIST_FILE)]
    samples = [{"file": f, "trials": read_rows(f)} for f in sample_files]

    data = {
        "text": text,
        "samples": samples,
        "practice": {"file": PRACTICE_FILE, "trials": read_rows(PRACTICE_FILE)[0:6]},
        "blocks": {
            group: [{"file": f, "trials": read_rows(f)} for f in files]
            for group, files in AMS_FILES.items()
        },
    }
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by build_stimuli.py from the PsychoPy spreadsheets. Do not edit by hand.\n")
        fh.write("window.AMS_DATA = ")
        json.dump(data, fh, ensure_ascii=False, indent=1)
        fh.write(";\n")
    n = sum(len(b["trials"]) for g in data["blocks"].values() for b in g)
    print(f"Wrote {OUT}: {len(samples)} sample sheets, "
          f"{len(data['practice']['trials'])} practice trials, {n} test trials")


if __name__ == "__main__":
    main()
